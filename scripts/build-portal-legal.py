#!/usr/bin/env python3
"""Render standalone legal pages from canonical notices using the existing PHP parser."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAGES = {
    "terms.es": "terminos-y-condiciones.html",
    "privacy.es": "aviso-de-privacidad.html",
    "terms.en": "terms-and-conditions.html",
    "privacy.en": "privacy-notice.html",
}
COPY = {
    "es": ["Volver a Generosity", "Aviso de privacidad", "Términos y condiciones", "Contacto", "Saltar al contenido", "Idioma"],
    "en": ["Back to Generosity", "Privacy notice", "Terms and conditions", "Contact", "Skip to content", "Language"],
}
php = '''<?php
require '/app/vendor/autoload.php';
$pages = [];
foreach (['terms.es', 'privacy.es', 'terms.en', 'privacy.en'] as $key) {
    $pages[$key] = Illuminate\\Support\\Str::markdown(file_get_contents('/app/resources/legal/'.$key.'.md'), ['html_input' => 'strip', 'allow_unsafe_links' => false]);
}
echo json_encode($pages, JSON_THROW_ON_ERROR);
'''
rendered = json.loads(subprocess.check_output(
    ["docker", "compose", "exec", "-T", "app", "php"],
    cwd=ROOT / "backend", input=php.encode(),
))
for key, filename in PAGES.items():
    document, locale = key.split(".")
    home, privacy, terms, contact, skip, language = COPY[locale]
    title = privacy if document == "privacy" else terms
    body = rendered[key]
    for target, path in PAGES.items():
        doc, lang = target.split(".")
        body = body.replace(f"https://api.generosity.global/legal/{doc}?locale={lang}", path)
    page = f'''<!doctype html>
<!-- Generated by scripts/build-portal-legal.py from backend/resources/legal; edit the source notices. -->
<html lang="{locale}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{title} — Generosity</title>
  <link rel="icon" href="assets/favicon.png" type="image/png">
  <link rel="stylesheet" href="styles.css?v=20261101-layout">
</head>
<body class="legal-page">
  <a class="skip" href="#contenido">{skip}</a>
  <header class="legal-header">
    <a class="brand" href="./"><img src="assets/wordmark.svg" alt="Generosity" width="1037" height="206"></a>
    <nav aria-label="{language}"><a href="{PAGES[document+'.es']}" lang="es" {'aria-current="page"' if locale == 'es' else ''}>Español</a><a href="{PAGES[document+'.en']}" lang="en" {'aria-current="page"' if locale == 'en' else ''}>English</a></nav>
  </header>
  <main id="contenido" class="legal-document" tabindex="-1">
    <a class="legal-back" href="./">← {home}</a>
    <article>{body}</article>
  </main>
  <footer class="legal-footer"><nav><a href="{PAGES['privacy.'+locale]}">{privacy}</a><a href="{PAGES['terms.'+locale]}">{terms}</a><a href="mailto:notificaciones@generosity.global">{contact}</a></nav></footer>
</body>
</html>
'''
    destination = ROOT / "portal" / filename
    if "--check" in sys.argv:
        if not destination.is_file() or destination.read_text() != page:
            raise SystemExit(f"Regenerate stale legal page: {filename}")
    else:
        destination.write_text(page)
    print(filename)
