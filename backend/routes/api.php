<?php

use App\Http\Controllers\AuthController;
use App\Http\Controllers\BrowserAuthController;
use App\Http\Controllers\CatalogController;
use App\Http\Controllers\CenterApplicationController;
use App\Http\Controllers\ClientSyncController;
use App\Http\Controllers\ContributionController;
use App\Http\Controllers\FeatureController;
use App\Http\Controllers\NotificationController;
use App\Http\Controllers\OpportunityController;
use App\Http\Controllers\ParticipationController;
use App\Http\Controllers\VisitController;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Route;

Route::prefix('v1')->group(function () {
    Route::post('auth/exchange', [BrowserAuthController::class, 'exchange'])->middleware('throttle:identity');
    Route::get('health', function () {
        DB::table('migrations')->count();

        return ['status' => 'ready', 'apiVersion' => 1, 'payments' => 'disabled'];
    });
    Route::get('features', [FeatureController::class, 'publicFeatures']);
    Route::get('centers', [CatalogController::class, 'centers']);
    Route::get('sync/catalog', [ClientSyncController::class, 'catalog']);
    Route::get('centers/{center}', [CatalogController::class, 'center']);
    Route::get('needs', [CatalogController::class, 'needs']);
    Route::get('needs/{need}', [CatalogController::class, 'need']);
    Route::get('needs/{need}/progress', [OpportunityController::class, 'progress']);
    Route::get('campaigns', [OpportunityController::class, 'campaigns']);
    Route::get('campaigns/{campaign}', [OpportunityController::class, 'campaign']);
    Route::get('occurrences', [OpportunityController::class, 'occurrences']);
    Route::get('occurrences/{occurrence}', [OpportunityController::class, 'occurrence']);
    Route::get('meals', [OpportunityController::class, 'meals']);
    Route::get('meals/{meal}', [OpportunityController::class, 'meal'])->whereUuid('meal');
    Route::get('opportunities/{kind}/{id}', [OpportunityController::class, 'preview'])->where('kind', 'need|center|campaign|occurrence|meal');
    Route::get('outcome-updates/{outcome}', [OpportunityController::class, 'outcome'])->whereUuid('outcome');
    Route::middleware('throttle:accounts')->prefix('auth')->group(function () {
        Route::post('register', [AuthController::class, 'register']);
        Route::post('login', [AuthController::class, 'login']);
        Route::post('verification', [AuthController::class, 'resend']);
        Route::get('verify/{id}/{hash}', [AuthController::class, 'verify'])->middleware('signed')->name('verification.verify');
        Route::post('forgot-password', [AuthController::class, 'forgot']);
        Route::post('reset-password', [AuthController::class, 'reset']);
    });
    Route::middleware(['auth:sanctum', 'verified'])->group(function () {
        Route::get('me/notifications', [NotificationController::class, 'inbox']);
        Route::get('me/notification-preferences', [NotificationController::class, 'showPreferences']);
        Route::post('me/notification-preferences', [NotificationController::class, 'preferences']);
        Route::get('me/follows', [ParticipationController::class, 'follows']);
        Route::get('me/enrollments', [ParticipationController::class, 'enrollments']);
        Route::post('campaigns', [ParticipationController::class, 'createCampaign']);
        Route::post('staff/centers/{center}/occurrences', [ParticipationController::class, 'publishOccurrence']);
        Route::put('staff/centers/{center}/occurrences/{occurrence}', [ParticipationController::class, 'updateOccurrence']);
        Route::post('staff/centers/{center}/occurrences/{occurrence}/cancel', [ParticipationController::class, 'cancelOccurrence']);
        Route::post('occurrences/{occurrence}/enrollments', [ParticipationController::class, 'enroll']);
        Route::post('occurrences/{occurrence}/assisted-enrollments', [ParticipationController::class, 'enrollAssisted']);
        Route::post('occurrences/{occurrence}/attendance', [ParticipationController::class, 'attendance']);
        Route::post('enrollments/{enrollment}/cancel', [ParticipationController::class, 'cancelEnrollment'])->whereUuid('enrollment');
        Route::post('staff/centers/{center}/meal-plans', [ParticipationController::class, 'createMealPlan']);
        Route::post('meal-plans/{plan}/approval', [ParticipationController::class, 'approveMealPlan'])->whereUuid('plan');
        Route::post('meal-plans/{plan}/withdrawal', [ParticipationController::class, 'withdrawMealPlan'])->whereUuid('plan');
        Route::post('meal-slots/{slot}/commitments', [ParticipationController::class, 'commitMeal'])->whereUuid('slot');
        Route::post('staff/centers/{center}/assisted-subjects', [ParticipationController::class, 'createSubject']);
        Route::post('assisted-claims', [ParticipationController::class, 'claim']);
        Route::post('assisted-claims/{claim}/decision', [ParticipationController::class, 'decideClaim'])->middleware('throttle:participation-reviews')->whereUuid('claim');
        Route::post('staff/centers/{center}/outcome-updates', [ParticipationController::class, 'createOutcome']);
        Route::post('outcome-updates/{outcome}/transition', [ParticipationController::class, 'transitionOutcome'])->whereUuid('outcome');
        Route::post('follows', [ParticipationController::class, 'follow']);
        Route::post('follows/{follow}/unsubscribe', [ParticipationController::class, 'unsubscribe'])->whereUuid('follow');
        Route::get('operator/funnel', [ParticipationController::class, 'funnel']);
        Route::post('me/push-installations/{installation}', [NotificationController::class, 'register'])->whereUuid('installation');
        Route::post('me/notifications/{notice}/read', [NotificationController::class, 'read'])->whereUuid('notice');
        Route::get('me/center-applications', [CenterApplicationController::class, 'index']);
        Route::post('center-applications', [CenterApplicationController::class, 'store'])->middleware('throttle:center-applications');
        Route::get('center-applications/{application}', [CenterApplicationController::class, 'show'])->middleware('throttle:center-application-cases')->whereUuid('application');
        Route::post('center-applications/{application}/decision', [CenterApplicationController::class, 'decide'])->middleware('throttle:center-application-reviews')->whereUuid('application');
        Route::post('center-applications/{application}/acceptance', [CenterApplicationController::class, 'acceptMembership'])->middleware('throttle:center-application-reviews')->whereUuid('application');
        Route::post('center-applications/{application}/withdrawal', [CenterApplicationController::class, 'withdraw'])->middleware('throttle:center-application-reviews')->whereUuid('application');
        Route::get('sync/account', [ClientSyncController::class, 'account']);
        Route::get('staff/centers', [ClientSyncController::class, 'staffCenters']);
        Route::get('me/features', [FeatureController::class, 'accountFeatures']);
        Route::get('me', fn (Request $request) => ['user' => $request->user()]);
        Route::post('auth/logout', [AuthController::class, 'logout']);
        Route::get('me/contributions', [ContributionController::class, 'history']);
        Route::get('me/impact', [ContributionController::class, 'impact']);
        Route::post('contributions', [ContributionController::class, 'store']);
        Route::post('visits', [VisitController::class, 'store']);
        Route::get('contributions/{contribution}', [ContributionController::class, 'show']);
        Route::post('contributions/{contribution}/transition', [ContributionController::class, 'transition']);
        Route::get('staff/centers/{center}/contributions', [ContributionController::class, 'centerHistory']);
        Route::get('staff/centers/{center}/needs', [CatalogController::class, 'staffNeeds']);
        Route::post('staff/centers/{center}/needs', [CatalogController::class, 'createNeed']);
        Route::put('staff/centers/{center}/needs/{need}', [CatalogController::class, 'updateNeed']);
    });
});
